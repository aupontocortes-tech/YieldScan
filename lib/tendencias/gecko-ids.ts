export function geckoIdFromSymbol(symbol: string | null | undefined): string | null {
  if (!symbol) return null
  const key = symbol.toUpperCase().replace(/[^A-Z0-9]/g, '')
  return SYMBOL_GECKO_ID[key] ?? null
}
